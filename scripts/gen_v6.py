LEGACY_ENTRIES = {
    ("synthetics", "v202202"): {
        "stability": "stable",
        "status": "deprecated",
        "transport": "grpc",
        "python": "kentik_api.KentikAPI.synthetics",
        "note": "1.x client (KentikSynthClient); version removed from api-schema-public in 702809b",
        "surface": [
            "get_all_agents",
            "get_agent",
            "update_agent",
            "delete_agent",
            "get_all_tests",
            "get_test",
            "create_test",
            "update_test",
            "delete_test",
            "set_test_status",
            "results_for_tests",
            "trace_for_test",
        ],
    },
}
LEGACY_EXTRA = {
    ("cloud_export", "v202101beta1"): "also kentik_api.KentikAPI.cloud_export (1.x gRPC client, deprecated)",
}


def render_manifest(pvs: list[PackageVersion]) -> str:
    stable_aliases, exp_aliases = compute_aliases(pvs)
    alias_of: dict[str, str] = {}
    for al in stable_aliases:
        if al.target:
            alias_of[al.target.module] = f"client.{al.name}"
        for v in (al.composite or {}).values():
            alias_of[v.module] = f"client.{al.name}"
    for al in exp_aliases:
        if al.target:
            alias_of[al.target.module] = f"client.experimental.{al.name}"
    by_pkg: dict[str, list[PackageVersion]] = collections.defaultdict(list)
    for pv in pvs:
        by_pkg[pv.package].append(pv)
    services: list[dict[str, Any]] = []
    for pv in sorted(pvs, key=lambda p: (p.package, version_key(p.version))):
        entry: dict[str, Any] = {"service": pv.package, "version": pv.version, "stability": pv.stability}
        if pv.operations:
            if pv.stability != "stable":
                status = "experimental"
                python = f"client.experimental.{pv.module}"
            else:
                newer = [
                    v
                    for v in by_pkg[pv.package]
                    if v.stability == "stable" and version_key(v.version) > version_key(pv.version) and v.operations
                ]
                covered = set().union(*(set(v.rest_services) for v in newer)) if newer else set()
                status = "deprecated" if set(pv.rest_services) <= covered else "supported"
                python = f"client.{pv.module}"
            entry.update(status=status, transport="rest", python=python)
            if pv.module in alias_of:
                entry["alias"] = alias_of[pv.module]
            entry["surface"] = [f"{op.grpc_service}/{op.rpc}" for op in pv.operations]
            if (pv.package, pv.version) in LEGACY_EXTRA:
                entry["note"] = LEGACY_EXTRA[(pv.package, pv.version)]
        elif pv.grpc_services:
            entry.update(
                status="unsupported",
                transport="grpc-only",
                surface=[],
                note="no google.api.http bindings: gRPC only, not reachable through the REST client "
                + "(services: "
                + ", ".join(pv.grpc_services)
                + ")",
            )
        else:
            entry.update(
                status="supported", transport="n/a", surface=["message types only (inlined into dependent models)"]
            )
        services.append(entry)
    for (svc, ver), extra in LEGACY_ENTRIES.items():
        services.append({"service": svc, "version": ver, **extra})
    services.sort(key=lambda e: (e["service"], version_key(e["version"])))
    manifest = {
        "schema_source": {
            "repo": SOURCE["repo"],
            "ref": SOURCE["ref"],
            "ref_date": SOURCE.get("ref_date"),
            "legacy_ref": SOURCE.get("legacy_ref"),
            "path": "gen/openapiv3",
        },
        "package": {
            "pypi": "kentik-api",
            "import": "kentik_api",
            "client": ["kentik_api.KentikClient", "kentik_api.AsyncKentikClient"],
        },
        "services": services,
        "legacy": [
            {
                "api": "v5",
                "status": "deprecated",
                "python": "kentik_api.KentikAPI",
                "surface": [
                    "alerting",
                    "batch",
                    "custom_applications",
                    "custom_dimensions",
                    "device_labels",
                    "devices",
                    "my_kentik_portal",
                    "plans",
                    "query",
                    "saved_filters",
                    "sites",
                    "tags",
                    "users",
                ],
            }
        ],
    }
    return json.dumps(manifest, indent=2) + "\n"


def render_services_init(pvs: list[PackageVersion]) -> str:
    rows = "\n".join(f"* ``{pv.module}``: ``{pv.proto_package}`` ({pv.stability})" for pv in pvs if pv.operations)
    return HEADER + pydoc(f"Generated v6 service packages.\n\n{rows}", 0) + "\n"


