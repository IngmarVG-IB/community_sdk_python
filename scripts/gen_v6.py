"""v6 stage of ``scripts/generate.py``: models, service wrappers, client registry and manifest.

Input: ``schema/openapiv3/kentik/<package>/<version>/*.json`` (OpenAPI 3.0 emitted by grpc-gateway for
api-schema-public). Output:

* ``kentik_api/v6/services/<package>_<version>/models.py``: pydantic v2 models (datamodel-code-generator)
* ``kentik_api/v6/services/<package>_<version>/__init__.py``: sync and async service wrappers
* ``kentik_api/v6/_services.py``: client mixins (versioned attributes, aliases, experimental namespace)
* ``kentik-api.json``: coverage manifest
"""

