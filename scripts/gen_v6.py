@dataclass
class Alias:
    name: str
    target: PackageVersion | None  # simple alias
    composite: dict[str, PackageVersion] | None = None  # grpc service -> version providing it


def compute_aliases(pvs: list[PackageVersion]) -> tuple[list[Alias], list[Alias]]:
    by_pkg: dict[str, list[PackageVersion]] = collections.defaultdict(list)
    for pv in pvs:
        if pv.operations:
            by_pkg[pv.package].append(pv)
    stable_aliases: list[Alias] = []
    experimental_aliases: list[Alias] = []
    for pkg, versions in sorted(by_pkg.items()):
        name = pkg.replace("/", "_")
        stable = sorted((v for v in versions if v.stability == "stable"), key=lambda v: version_key(v.version))
        if stable:
            newest = stable[-1]
            provider: dict[str, PackageVersion] = {}
            for v in stable:
                for s in v.rest_services:
                    provider[s] = v
            if all(p is newest for p in provider.values()):
                stable_aliases.append(Alias(name, newest))
            else:
                stable_aliases.append(Alias(name, None, dict(sorted(provider.items()))))
        else:
            pre = sorted(versions, key=lambda v: version_key(v.version))
            experimental_aliases.append(Alias(name, pre[-1]))
    return stable_aliases, experimental_aliases


def render_registry(pvs: list[PackageVersion]) -> str:
    rest = [pv for pv in pvs if pv.operations]
    stable = [pv for pv in rest if pv.stability == "stable"]
    pre = [pv for pv in rest if pv.stability != "stable"]
    stable_aliases, exp_aliases = compute_aliases(pvs)
    out = [
        HEADER,
        pydoc("Service attributes of :class:`KentikClient` / :class:`AsyncKentikClient` (generated).", 0),
        "",
        "from __future__ import annotations",
        "",
        "import importlib",
        "from functools import cached_property",
        "from typing import TYPE_CHECKING, Any, cast",
        "",
        "from ._core.transport import AsyncTransport, SyncTransport",
        "",
        "if TYPE_CHECKING:",
    ]
    for pv in rest:
        out.append(f"    from .services.{pv.module} import Async{pv.ns_class}, {pv.ns_class}")
    composite_imports = set()
    for al in stable_aliases:
        if al.composite:
            for s, pv in al.composite.items():
                composite_imports.add(
                    f"    from .services.{pv.module} import Async{s} as Async{s}_{pv.version}, {s} as {s}_{pv.version}"
                )
    out += sorted(composite_imports)
    out += [
        "",
        "",
        "def _load(module: str, name: str) -> Any:",
        '    return getattr(importlib.import_module(f"kentik_api.v6.services.{module}"), name)',
        "",
        "",
        "STABLE = " + json.dumps({pv.module: f"{pv.package}/{pv.version}" for pv in stable}, indent=4),
        "EXPERIMENTAL = " + json.dumps({pv.module: f"{pv.package}/{pv.version}" for pv in pre}, indent=4),
        "ALIASES = "
        + json.dumps(
            {
                al.name: (al.target.module if al.target else {s: v.module for s, v in (al.composite or {}).items()})
                for al in stable_aliases
            },
            indent=4,
        ),
        "EXPERIMENTAL_ALIASES = "
        + json.dumps({al.name: al.target.module for al in exp_aliases if al.target}, indent=4),
        "",
    ]
    for flavour in ("sync", "async"):
        a = "" if flavour == "sync" else "Async"
        transport = "SyncTransport" if flavour == "sync" else "AsyncTransport"
        # composite alias classes
        for al in stable_aliases:
            if not al.composite:
                continue
            cls = f"{a}{pascal(al.name)}Latest"
            out += ["", f"class {cls}:"]
            out.append(
                pydoc(
                    f"Newest stable version of each gRPC service in ``kentik.{al.name.replace('_', '.')}`` ({flavour}).",
                    4,
                )
            )
            out += [
                "",
                "    def __init__(self, services: _" + a + "StableServices) -> None:",
                "        self._services = services",
            ]
            for s, pv in al.composite.items():
                out += [
                    "",
                    "    @property",
                    f"    def {service_attr(s)}(self) -> {a}{s}_{pv.version}:",
                    pydoc(f"``{pv.proto_package}.{s}``", 8),
                    f"        return self._services.{pv.module}.{service_attr(s)}",
                ]
        # experimental namespace
        out += ["", "", f"class {a}Experimental:"]
        out.append(
            pydoc(
                f"Alpha and beta API versions ({flavour}). No compatibility guarantees: see the API life-cycle policy in api-schema-public.",
                4,
            )
        )
        out += ["", f"    def __init__(self, transport: {transport}) -> None:", "        self._transport = transport"]
        for pv in pre:
            out += [
                "",
                "    @cached_property",
                f"    def {pv.module}(self) -> {a}{pv.ns_class}:",
                pydoc(f"``{pv.proto_package}`` ({pv.stability}).", 8),
                f'        return cast("{a}{pv.ns_class}", _load("{pv.module}", "{a}{pv.ns_class}")(self._transport))',
            ]
        for al in exp_aliases:
            assert al.target
            out += [
                "",
                "    @property",
                f"    def {al.name}(self) -> {a}{al.target.ns_class}:",
                pydoc(f"Alias of :attr:`{al.target.module}` (newest version; no stable version exists).", 8),
                f"        return self.{al.target.module}",
            ]
        # stable services mixin
        out += ["", "", f"class _{a}StableServices:"]
        out.append(pydoc(f"Stable API versions and aliases ({flavour}).", 4))
        out += ["", f"    _transport: {transport}"]
        out += [
            "",
            "    @cached_property",
            f"    def experimental(self) -> {a}Experimental:",
            pydoc("Alpha and beta API versions.", 8),
            f"        return {a}Experimental(self._transport)",
        ]
        for pv in stable:
            out += [
                "",
                "    @cached_property",
                f"    def {pv.module}(self) -> {a}{pv.ns_class}:",
                pydoc(f"``{pv.proto_package}``.", 8),
                f'        return cast("{a}{pv.ns_class}", _load("{pv.module}", "{a}{pv.ns_class}")(self._transport))',
            ]
        for al in stable_aliases:
            if al.target:
                out += [
                    "",
                    "    @property",
                    f"    def {al.name}(self) -> {a}{al.target.ns_class}:",
                    pydoc(f"Alias of :attr:`{al.target.module}`, the newest stable version.", 8),
                    f"        return self.{al.target.module}",
                ]
            else:
                cls = f"{a}{pascal(al.name)}Latest"
                out += [
                    "",
                    "    @cached_property",
                    f"    def {al.name}(self) -> {cls}:",
                    pydoc("Newest stable version of each gRPC service (versions differ per service).", 8),
                    f"        return {cls}(self)",
                ]
    return "\n".join(out) + "\n"


