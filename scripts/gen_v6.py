def _model(pv: PackageVersion, schema: str | None) -> str:
    if schema is None:
        return "EmptyResponse"
    cls = pv.renames[schema]
    if cls not in pv.fields:
        raise SystemExit(f"{pv.module}: model {cls} (schema {schema}) was not generated")
    return f"models.{cls}"


def detect_pagination(pv: PackageVersion, op: Operation) -> None:
    resp = pv.schemas.get(op.response_schema or "", {})
    arrays = [(k, v) for k, v in resp.get("properties", {}).items() if v.get("type") == "array"]
    if len(arrays) != 1:
        return
    items_json, items_schema = arrays[0]
    found: dict[str, str] | None = None
    qnames = {p.api_name for p in op.query_params}
    for prefix in PAGINATION_PREFIXES:
        if f"{prefix}limit" in qnames and f"{prefix}offset" in qnames:
            found = {"location": "query", "limit": f"{prefix}limit", "offset": f"{prefix}offset"}
            break
    if not found and op.body_schema:
        body = pv.schemas.get(op.body_schema, {})
        pag_ref = _ref_name(body.get("properties", {}).get("pagination"))
        pag = pv.schemas.get(pag_ref or "", {}).get("properties", {})
        if "limit" in pag and "offset" in pag:
            found = {"location": "body", "limit": "pagination.limit", "offset": "pagination.offset"}
    if not found:
        return
    resp_cls = pv.renames[op.response_schema or ""]
    found["items"] = pv.fields[resp_cls].get(items_json, snake(items_json))
    op.pagination = found
    op.item_schema = _ref_name(items_schema.get("items"))


def _sig(op: Operation, pv: PackageVersion, *, paginated: bool) -> tuple[list[str], list[str]]:
    """Return (positional params, keyword-only params) source fragments."""
    pos = [f"{p.py_name}: {p.annotation}" for p in op.path_params]
    if op.body_schema:
        btype = f"{_model(pv, op.body_schema)} | Mapping[str, Any]"
        if op.body_required and not (paginated and op.pagination and op.pagination["location"] == "body"):
            pos.append(f"body: {btype}")
        else:
            pos.append(f"body: {btype} | None = None")
    kw = []
    skip = set()
    if paginated and op.pagination and op.pagination["location"] == "query":
        skip = {op.pagination["limit"], op.pagination["offset"]}
    for p in op.query_params:
        if p.api_name in skip:
            continue
        kw.append(f"{p.py_name}: {p.annotation} | None = None")
    if paginated:
        kw.append("page_size: int = DEFAULT_PAGE_SIZE")
    kw.append("timeout: Timeout = None")
    return pos, kw


def _call_args(op: Operation, *, paginated: bool) -> list[str]:
    args = []
    if op.path_params:
        args.append("path={" + ", ".join(f"{p.api_name!r}: {p.py_name}" for p in op.path_params) + "}")
    skip = set()
    if paginated and op.pagination and op.pagination["location"] == "query":
        skip = {op.pagination["limit"], op.pagination["offset"]}
    q = [p for p in op.query_params if p.api_name not in skip]
    if q:
        args.append("query={" + ", ".join(f"{p.api_name!r}: {p.py_name}" for p in q) + "}")
    if op.body_schema:
        args.append("body=body")
    if paginated:
        args.append("page_size=page_size")
    args.append("timeout=timeout")
    return args


def _ep_name(op: Operation) -> str:
    return f"_{snake(op.grpc_service).upper()}_{op.py_name.upper()}"


def _docstring(op: Operation, pv: PackageVersion, extra: str = "") -> str:
    parts = [op.summary.strip() or op.rpc]
    if op.description.strip() and op.description.strip() != op.summary.strip():
        parts.append(op.description.strip())
    if extra:
        parts.append(extra)
    parts.append(f"RPC ``{pv.proto_package}.{op.grpc_service}/{op.rpc}`` (``{op.http_method} {op.path}``).")
    return pydoc("\n\n".join(parts), 8)


def _def(header: str, pos: list[str], kw: list[str], ret: str) -> str:
    params = ["self", *pos]
    if kw:
        params += ["*", *kw]
    return f"    {header}(" + ", ".join(params) + f") -> {ret}:"


def render_service_module(pv: PackageVersion) -> str:
    head: list[str] = [HEADER, pydoc(f"Client for ``{pv.proto_package}`` ({pv.stability}).", 0), ""]
    exports = sorted(
        [*pv.rest_services, *("Async" + s for s in pv.rest_services), pv.ns_class, "Async" + pv.ns_class, "models"]
    )
    lines: list[str] = [f"__all__ = {exports!r}", ""]
    for op in pv.operations:
        detect_pagination(pv, op)
        resp = _model(pv, op.response_schema)
        svc = f"{pv.proto_package}.{op.grpc_service}"
        lines.append(
            f"{_ep_name(op)} = Endpoint({svc!r}, {op.rpc!r}, {op.http_method!r}, {op.path!r}, {resp}, "
            f"idempotent={is_idempotent(op.http_method, op.rpc)}, has_body={bool(op.body_schema)})"
        )
        if op.pagination:
            p = op.pagination
            lines.append(
                f"{_ep_name(op)}_PAGE = Pagination({p['location']!r}, {p['limit']!r}, {p['offset']!r}, {p['items']!r})"
            )
    lines.append("")
    by_service: dict[str, list[Operation]] = collections.defaultdict(list)
    for op in pv.operations:
        by_service[op.grpc_service].append(op)
    for flavour in ("sync", "async"):
        for svc_name, ops in sorted(by_service.items()):
            cls = svc_name if flavour == "sync" else f"Async{svc_name}"
            base = "SyncService" if flavour == "sync" else "AsyncService"
            lines += ["", f"class {cls}({base}):"]
            lines.append(pydoc(f"``{pv.proto_package}.{svc_name}`` ({flavour}).", 4))
            for op in ops:
                resp = _model(pv, op.response_schema)
                pos, kw = _sig(op, pv, paginated=False)
                prefix = "def" if flavour == "sync" else "async def"
                lines += ["", _def(f"{prefix} {op.py_name}", pos, kw, resp), _docstring(op, pv)]
                aw = "" if flavour == "sync" else "await "
                lines.append(
                    f"        return {aw}self._transport.request({_ep_name(op)}, "
                    + ", ".join(_call_args(op, paginated=False))
                    + ")"
                )
                if op.pagination:
                    item = f"models.{pv.renames[op.item_schema]}" if op.item_schema else "Any"
                    it = "Iterator" if flavour == "sync" else "AsyncIterator"
                    pos, kw = _sig(op, pv, paginated=True)
                    note = (
                        f"Iterate over all ``{op.pagination['items']}`` of :meth:`{op.py_name}`, following "
                        f"``{op.pagination['offset']}``/``{op.pagination['limit']}`` pagination."
                    )
                    lines += ["", _def(f"def iter_{op.py_name}", pos, kw, f"{it}[{item}]"), _docstring(op, pv, note)]
                    lines.append(
                        f"        return self._paginate({_ep_name(op)}, {_ep_name(op)}_PAGE, "
                        + ", ".join(_paginate_args(op))
                        + ")"
                    )
    lines += render_namespaces(pv, by_service)
    body = "\n".join(lines)

    def used(token: str) -> bool:
        return re.search(token, body) is not None

    abc = [n for n in ("AsyncIterator", "Iterator", "Mapping", "Sequence") if used(rf"(?<![A-Za-z]){n}\[")]
    core = [
        ("..._core.endpoint", [n for n in ("Endpoint", "Pagination") if used(rf"\b{n}\(")]),
        ("..._core.models", ["EmptyResponse"] if used(r"\bEmptyResponse\b") else []),
        ("..._core.service", [n for n in ("DEFAULT_PAGE_SIZE", "AsyncService", "SyncService") if used(rf"\b{n}\b")]),
        ("..._core.transport", [n for n in ("AsyncTransport", "SyncTransport", "Timeout") if used(rf"\b{n}\b")]),
    ]
    head += ["from __future__ import annotations", ""]
    if abc:
        head.append(f"from collections.abc import {', '.join(abc)}")
    if used(r"\bdatetime\b"):
        head.append("from datetime import datetime")
    if used(r"\bAny\b"):
        head.append("from typing import Any")
    head.append("")
    head += [f"from {mod} import {', '.join(names)}" for mod, names in core if names]
    head += ["from . import models", ""]
    return "\n".join(head) + "\n" + body + "\n"


def _paginate_args(op: Operation) -> list[str]:
    args = [
        "path={" + ", ".join(f"{p.api_name!r}: {p.py_name}" for p in op.path_params) + "}"
        if op.path_params
        else "path=None"
    ]
    skip = (
        {op.pagination["limit"], op.pagination["offset"]}
        if op.pagination and op.pagination["location"] == "query"
        else set()
    )
    q = [p for p in op.query_params if p.api_name not in skip]
    args.append("query={" + ", ".join(f"{p.api_name!r}: {p.py_name}" for p in q) + "}" if q else "query=None")
    args.append("body=body" if op.body_schema else "body=None")
    args += ["page_size=page_size", "timeout=timeout"]
    return args


def is_idempotent(http_method: str, rpc: str) -> bool:
    """Same rule as ``kentik_api.v6._core.endpoint.Endpoint.is_idempotent`` (kept in sync by a test).

    Not imported, so the generator works even when the generated package is stale or missing.
    """
    if http_method.upper() in {"GET", "HEAD", "OPTIONS", "PUT", "DELETE"}:
        return True
    return rpc.startswith(("Get", "List", "Search", "Query", "Fetch", "Find"))


def flattenable(by_service: dict[str, list[Operation]]) -> bool:
    names: list[str] = []
    for ops in by_service.values():
        for op in ops:
            names.append(op.py_name)
            if op.pagination:
                names.append(f"iter_{op.py_name}")
    attrs = {service_attr(s) for s in by_service}
    return len(names) == len(set(names)) and not (attrs & set(names))


def render_namespaces(pv: PackageVersion, by_service: dict[str, list[Operation]]) -> list[str]:
    lines: list[str] = []
    flat = flattenable(by_service)
    for flavour in ("sync", "async"):
        a = "" if flavour == "sync" else "Async"
        transport = "SyncTransport" if flavour == "sync" else "AsyncTransport"
        services = sorted(by_service)
        bases = ", ".join(f"{a}{s}" for s in services) if flat else ""
        lines += ["", "", f"class {a}{pv.ns_class}({bases}):" if bases else f"class {a}{pv.ns_class}:"]
        how = (
            "Methods of every gRPC service are available directly and through the per-service attributes."
            if flat
            else "Method names collide across gRPC services; use the per-service attributes."
        )
        lines.append(pydoc(f"``{pv.proto_package}`` ({pv.stability}, {flavour}).\n\n{how}", 4))
        lines += ["", f"    def __init__(self, transport: {transport}) -> None:"]
        if flat:
            lines.append(f"        {a}{services[0]}.__init__(self, transport)")
        for s in services:
            lines.append(f"        self.{service_attr(s)} = {a}{s}(transport)")
            lines.append(pydoc(f"``{pv.proto_package}.{s}``", 8))
    return lines


