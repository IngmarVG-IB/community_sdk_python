def class_name(n: str) -> str:
    """PascalCase identifier: drop non-alphanumerics, capitalise after each removed separator."""
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^0-9A-Za-z]+", n) if p)


def compute_renames(pv: PackageVersion) -> dict[str, str]:
    def strip(n: str) -> str:
        m = SCHEMA_PREFIX_RE.match(n)
        return class_name(n[m.end() :] if m else n)

    candidates = {k: strip(k) for k in pv.schemas}
    counts = collections.Counter(candidates.values())
    renames: dict[str, str] = {}
    for original, cand in sorted(candidates.items()):
        if counts[cand] == 1 and not keyword.iskeyword(cand):
            renames[original] = cand
        else:
            renames[original] = class_name(original)
    if len(set(renames.values())) != len(renames):
        raise SystemExit(f"{pv.module}: schema rename collision")
    return renames


def _strip_defaults(schema: Any) -> Any:
    """Drop schema ``default`` values: proto3 defaults are implicit, and a model default would be sent
    back to the API as an explicit value."""
    if isinstance(schema, list):
        return [_strip_defaults(v) for v in schema]
    if not isinstance(schema, dict):
        return schema
    out: dict[str, Any] = {}
    for k, v in schema.items():
        if k == "default":
            continue
        if k in {"properties", "patternProperties"} and isinstance(v, dict):
            out[k] = {name: _strip_defaults(sub) for name, sub in v.items()}
        else:
            out[k] = _strip_defaults(v)
    return out


def _rewrite_refs(obj: Any, renames: dict[str, str]) -> Any:
    if isinstance(obj, dict):
        out = {}
        for k, v in obj.items():
            if k == "$ref" and isinstance(v, str) and v.startswith("#/components/schemas/"):
                out[k] = "#/components/schemas/" + renames[v.rsplit("/", 1)[-1]]
            else:
                out[k] = _rewrite_refs(v, renames)
        return out
    if isinstance(obj, list):
        return [_rewrite_refs(v, renames) for v in obj]
    return obj


CODEGEN_ARGS = [
    "--input-file-type=openapi",
    "--output-model-type=pydantic_v2.BaseModel",
    "--base-class=kentik_api.v6._core.models.KentikModel",
    "--target-python-version=3.11",
    "--snake-case-field",
    "--force-optional",
    "--use-annotated",
    "--use-standard-collections",
    "--use-union-operator",
    "--use-subclass-enum",
    "--capitalise-enum-members",
    "--use-schema-description",
    "--use-field-description",
    "--field-constraints",
    "--collapse-root-models",
    "--disable-timestamp",
    "--keep-model-order",
    "--openapi-scopes=schemas",
    "--formatters=ruff-format",
    "--naming-strategy=parent-prefixed",
]


def generate_models(pv: PackageVersion, out_dir: Path) -> None:
    pv.renames = compute_renames(pv)
    schemas = {pv.renames[k]: _strip_defaults(_rewrite_refs(v, pv.renames)) for k, v in sorted(pv.schemas.items())}
    spec = {
        "openapi": "3.0.0",
        "info": {"title": pv.proto_package, "version": pv.version},
        "paths": {},
        "components": {"schemas": schemas},
    }
    out = out_dir / "models.py"
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / f"{pv.module}.json"
        src.write_text(json.dumps(spec, indent=1, sort_keys=True))
        exe = Path(sys.executable).parent / "datamodel-codegen"
        subprocess.run(
            [str(exe), f"--input={src}", f"--output={out}", *CODEGEN_ARGS],
            check=True,
            capture_output=True,
            text=True,
        )
    text = out.read_text()
    # Open enums (unknown values become pseudo-members, see ADR 0005).
    text = text.replace("from enum import StrEnum\n", "")
    text = re.sub(r"^class (\w+)\(StrEnum\):", r"class \1(OpenEnum):", text, flags=re.M)
    text = text.replace(
        "from kentik_api.v6._core.models import KentikModel",
        "from kentik_api.v6._core.models import KentikModel, OpenEnum",
    )
    text = re.sub(r"^# generated by datamodel-codegen:\n#   filename: .*\n", "", text, flags=re.M)
    doc = f'"""Models for ``{pv.proto_package}`` (generated from the OpenAPI v3 schema)."""\n\n'
    out.write_text(HEADER + doc + text.lstrip())
    pv.fields = _model_fields(out)


def _model_fields(path: Path) -> dict[str, dict[str, str]]:
    tree = ast.parse(path.read_text())
    classes: dict[str, dict[str, str]] = {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        fields: dict[str, str] = {}
        for stmt in node.body:
            if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                alias = stmt.target.id
                for sub in ast.walk(stmt.annotation):
                    if isinstance(sub, ast.keyword) and sub.arg == "alias" and isinstance(sub.value, ast.Constant):
                        alias = str(sub.value.value)
                fields[alias] = stmt.target.id
        classes[node.name] = fields
    return classes


