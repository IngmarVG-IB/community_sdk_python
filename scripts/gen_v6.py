@dataclass
class Param:
    api_name: str
    py_name: str
    annotation: str
    description: str = ""


@dataclass
class Operation:
    rpc: str
    grpc_service: str
    http_method: str
    path: str
    summary: str
    description: str
    path_params: list[Param]
    query_params: list[Param]
    body_schema: str | None
    body_required: bool
    response_schema: str | None
    py_name: str = ""
    pagination: dict[str, str] | None = None
    item_schema: str | None = None


@dataclass
class PackageVersion:
    package: str  # e.g. "alerting/public"
    version: str  # e.g. "v202505"
    schemas: dict[str, Any]
    operations: list[Operation]
    grpc_services: list[str]  # all services declared (tags), including gRPC-only ones
    renames: dict[str, str] = field(default_factory=dict)
    fields: dict[str, dict[str, str]] = field(default_factory=dict)  # class -> json name -> attribute

    @property
    def module(self) -> str:
        return f"{self.package.replace('/', '_')}_{self.version}"

    @property
    def stability(self) -> str:
        return stability(self.version)

    @property
    def proto_package(self) -> str:
        return "kentik." + self.package.replace("/", ".") + "." + self.version

    @property
    def rest_services(self) -> list[str]:
        return sorted({op.grpc_service for op in self.operations})

    @property
    def ns_class(self) -> str:
        return pascal(self.module)


def _schema_type(schema: dict[str, Any], pv: PackageVersion, for_query: bool = True) -> str:
    if "$ref" in schema:
        return "Any"
    t = schema.get("type")
    fmt = schema.get("format")
    if t == "array":
        return f"Sequence[{_schema_type(schema.get('items', {}), pv)}]"
    if t == "string":
        if fmt == "date-time":
            return "datetime | str"
        if fmt in {"int64", "uint64"}:
            return "int | str"
        return "str"
    if t == "integer":
        return "int"
    if t == "number":
        return "float"
    if t == "boolean":
        return "bool"
    return "Any"


def _ref_name(schema: dict[str, Any] | None) -> str | None:
    if not schema or "$ref" not in schema:
        return None
    return str(schema["$ref"]).rsplit("/", 1)[-1]


def discover() -> list[PackageVersion]:
    result: list[PackageVersion] = []
    for vdir in sorted({p.parent for p in SPEC_ROOT.rglob("*.json")}):
        rel = vdir.relative_to(SPEC_ROOT)
        package, version = "/".join(rel.parts[:-1]), rel.parts[-1]
        schemas: dict[str, Any] = {}
        tags: set[str] = set()
        raw_ops: list[tuple[str, str, dict[str, Any]]] = []
        for spec_file in sorted(vdir.glob("*.json")):
            spec = json.loads(spec_file.read_text())
            for name, schema in spec.get("components", {}).get("schemas", {}).items():
                if name in schemas and schemas[name] != schema:
                    raise SystemExit(f"{rel}: conflicting definitions of schema {name}")
                schemas[name] = schema
            tags.update(t["name"] for t in spec.get("tags", []))
            request_bodies = spec.get("components", {}).get("requestBodies", {})
            for path, ops in spec.get("paths", {}).items():
                for method, op in ops.items():
                    rb = op.get("requestBody")
                    if rb and "$ref" in rb:  # shared components/requestBodies entry
                        op = {**op, "requestBody": request_bodies[rb["$ref"].rsplit("/", 1)[-1]]}
                    raw_ops.append((path, method, op))
        pv = PackageVersion(package, version, schemas, [], sorted(tags))
        pv.operations = _operations(pv, raw_ops)
        result.append(pv)
    return result


def _operations(pv: PackageVersion, raw_ops: list[tuple[str, str, dict[str, Any]]]) -> list[Operation]:
    by_rpc: dict[tuple[str, str], list[Operation]] = collections.defaultdict(list)
    for path, method, op in raw_ops:
        tags = op.get("tags") or ["Service"]
        rpc_name = op["operationId"]
        if rpc_name.startswith(tags[0] + "_"):  # grpc-gateway default operation id: <Service>_<Rpc>
            rpc_name = rpc_name[len(tags[0]) + 1 :]
        params = op.get("parameters", [])
        path_order = re.findall(r"\{([^}=]+)", path)
        path_params = sorted(
            (
                Param(
                    p["name"],
                    safe_param(p["name"]),
                    "str | int" if p.get("schema", {}).get("type") == "integer" else "str",
                    p.get("description", ""),
                )
                for p in params
                if p["in"] == "path"
            ),
            key=lambda p: path_order.index(p.api_name) if p.api_name in path_order else 99,
        )
        query_params = [
            Param(p["name"], safe_param(p["name"]), _schema_type(p.get("schema", {}), pv), p.get("description", ""))
            for p in params
            if p["in"] == "query"
        ]
        rb = op.get("requestBody")
        body_schema = None
        if rb:
            schema = rb["content"].get("application/json", {}).get("schema", {})
            body_schema = _ref_name(schema)
            if body_schema is None:
                # inline body (grpc-gateway emits these for some `body: "<field>"` bindings): name it
                # the way grpc-gateway names the others, <Service><Rpc>Body.
                body_schema = f"{tags[0]}{rpc_name}Body"
                if body_schema in pv.schemas:
                    raise SystemExit(f"{pv.module}: synthesized schema name {body_schema} already exists")
                pv.schemas[body_schema] = schema
        body_required = bool(rb and rb.get("required"))
        if body_schema and not pv.schemas.get(body_schema, {}).get("properties"):
            body_required = False
        resp = op.get("responses", {}).get("200", {}).get("content", {}).get("application/json", {}).get("schema")
        by_rpc[(tags[0], rpc_name)].append(
            Operation(
                rpc=rpc_name,
                grpc_service=tags[0],
                http_method=method.upper(),
                path=path,
                summary=op.get("summary", ""),
                description=op.get("description", ""),
                path_params=path_params,
                query_params=query_params,
                body_schema=body_schema,
                body_required=body_required,
                response_schema=_ref_name(resp),
            )
        )
    ops: list[Operation] = []
    for (_svc, _rpc), bindings in by_rpc.items():
        # additional_bindings: keep the binding with the most path parameters (the primary one in
        # api-schema-public); the others are aliases of the same RPC.
        best = max(bindings, key=lambda o: (len(o.path_params), -bindings.index(o)))
        ops.append(best)
    for o in ops:
        o.py_name = snake(o.rpc)
        names = [p.py_name for p in o.path_params + o.query_params]
        dupes = [n for n, c in collections.Counter(names).items() if c > 1]
        if dupes:
            raise SystemExit(f"{pv.module}.{o.rpc}: parameter name clash {dupes}")
    return sorted(ops, key=lambda o: (o.grpc_service, o.py_name))


