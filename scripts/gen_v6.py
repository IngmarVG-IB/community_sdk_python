def generate_v6() -> None:
    pvs = discover()
    shutil.rmtree(SERVICES, ignore_errors=True)
    SERVICES.mkdir(parents=True)
    rest = [pv for pv in pvs if pv.operations]

    def build(pv: PackageVersion) -> None:
        d = SERVICES / pv.module
        d.mkdir()
        generate_models(pv, d)
        (d / "__init__.py").write_text(render_service_module(pv))

    with ThreadPoolExecutor(max_workers=8) as pool:
        list(pool.map(build, rest))
    (SERVICES / "__init__.py").write_text(render_services_init(pvs))
    (V6 / "_services.py").write_text(render_registry(pvs))
    MANIFEST.write_text(render_manifest(pvs))
    ruff = Path(sys.executable).parent / "ruff"
    targets = [str(SERVICES), str(V6 / "_services.py")]
    subprocess.run([str(ruff), "check", "--fix", "--quiet", "--select", "I,F401,UP", *targets], check=False)
    subprocess.run([str(ruff), "format", "--quiet", *targets], check=True)
    n_ops = sum(len(pv.operations) for pv in rest)
    print(f"v6: {len(rest)} service versions, {n_ops} operations -> {SERVICES.relative_to(ROOT)}; {MANIFEST.name}")
